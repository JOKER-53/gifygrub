#!/usr/bin/env bash
# gifygrub::generate_theme WORKDIR THEME_NAME FRAME_FILE
#
# Writes a static theme.txt into WORKDIR using FRAME_FILE (one of the
# extracted frame_*.png) as the desktop background.
#
# NOTE: GRUB2 has no native mechanism for cycling a stack of image frames
# as an animation — this was verified directly against GRUB's C source
# (grub-core/gfxmenu/widget-box.c and gui_progress_bar.c). The `*_style`
# glob patterns GRUB supports are fixed 9-slice box parts (nw, n, ne, w,
# c, e, sw, s, se), not frame sequences, and the only per-tick redraw hook
# (`__timeout__`) is a 1Hz countdown callback that stops on user input.
# gifygrub therefore generates a STATIC theme from one representative
# frame, not an animation. See README.md > How it works.

gifygrub::generate_theme() {
    local workdir="$1"
    local theme_name="$2"
    local frame_file="$3"

    cat > "${workdir}/theme.txt" <<EOF
# Auto-generated by gifygrub v${GIFYGRUB_VERSION:-0.1.0}
# Theme: ${theme_name}
# Background frame: $(basename "$frame_file")
#
# NOTE: This is a static theme. GRUB2 has no native support for cycling
# through image frames as an animation — see README.md > How it works.

title-text: ""
desktop-image: "$(basename "$frame_file")"
EOF

    echo "    wrote ${workdir}/theme.txt (background: $(basename "$frame_file"))"
}

# gifygrub::pick_best_frame WORKDIR
#
# Selects a representative frame from the extracted frame_*.png set and
# echoes its path. Strategy: pick the middle frame by index — simple,
# deterministic, and avoids first/last frames which are often fade-in/out
# transitions in source GIFs.
gifygrub::pick_best_frame() {
    local workdir="$1"

    local frames=()
    while IFS= read -r -d '' f; do
        frames+=("$f")
    done < <(find "$workdir" -maxdepth 1 -name 'frame_*.png' -print0 | sort -z)

    local count=${#frames[@]}
    if (( count == 0 )); then
        echo "error: no frames found in ${workdir}" >&2
        exit 1
    fi

    local mid=$(( count / 2 ))
    echo "${frames[$mid]}"
}
