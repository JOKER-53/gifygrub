#!/usr/bin/env bash
# gifygrub::generate_theme WORKDIR THEME_NAME FPS
#
# Writes a theme.txt into WORKDIR that references the extracted frame_*.png
# files as a progress_bar-driven animation (see README.md > Limitations for
# why progress_bar, not a real animation widget, is what GRUB actually offers).

gifygrub::generate_theme() {
    local workdir="$1"
    local theme_name="$2"
    local fps="$3"

    # GRUB's progress_bar redraw isn't a true per-second timer; it's tied to
    # the boot countdown tick. We express delay as an approximate number of
    # ticks per frame so contributors can tune it per-GRUB-version later.
    local delay_ms=$(( 1000 / fps ))

    local frame_count
    frame_count="$(find "$workdir" -maxdepth 1 -name 'frame_*.png' | wc -l)"

    cat > "${workdir}/theme.txt" <<EOF
# Auto-generated by gifygrub v${GIFYGRUB_VERSION:-0.1.0}
# Theme: ${theme_name}
# Frames: ${frame_count}  Target fps: ${fps}  (~${delay_ms}ms/frame)
#
# NOTE: GRUB has no native animation timer. This block drives the frame
# cycle off the boot progress_bar widget, which is the only GRUB element
# that redraws on an interval. See README.md > Limitations.

title-text: ""
desktop-image: "frame_0001.png"

+ progress_bar {
    id = "__timeout__"
    left = 0
    top = 0
    width = 100%
    height = 100%
    show_text = false
    fg_color = "0,0,0"
    bg_color = "0,0,0"
    border_color = "0,0,0"
    file = "frame_*.png"
}
EOF

    echo "    wrote ${workdir}/theme.txt"
}
